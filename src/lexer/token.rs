//! Token kinds produced by the [lexer](super).

use crate::diagnostic::Pos;

#[derive(Debug, Clone, PartialEq)]
pub enum TokenKind {
    // keywords
    Let,
    Const,
    Fn,
    Return,
    If,
    Else,
    While,
    True,
    False,
    Struct,
    Extern,
    Import,
    For,
    In,
    Break,
    Continue,
    // literals / names
    Ident(String),
    Int(i64),
    Float(f64),
    Str(String),
    // operators
    Plus,
    Minus,
    Star,
    Slash,
    Percent,
    EqEq,
    NotEq,
    Lt,
    Le,
    Gt,
    Ge,
    AndAnd,
    OrOr,
    Bang,
    Assign,
    PlusEq,
    MinusEq,
    StarEq,
    SlashEq,
    PercentEq,
    Arrow,
    // punctuation
    Colon,
    Semi,
    Comma,
    LParen,
    RParen,
    LBrace,
    RBrace,
    LBracket,
    RBracket,
    Dot,
    DotDot,
    Eof,
}

impl TokenKind {
    /// Human-readable description used in parser error messages.
    pub fn describe(&self) -> String {
        use TokenKind as T;
        match self {
            T::Let => "'let'".into(),
            T::Const => "'const'".into(),
            T::Fn => "'fn'".into(),
            T::Return => "'return'".into(),
            T::If => "'if'".into(),
            T::Else => "'else'".into(),
            T::While => "'while'".into(),
            T::True => "'true'".into(),
            T::False => "'false'".into(),
            T::Struct => "'struct'".into(),
            T::Extern => "'extern'".into(),
            T::Import => "'import'".into(),
            T::For => "'for'".into(),
            T::In => "'in'".into(),
            T::Break => "'break'".into(),
            T::Continue => "'continue'".into(),
            T::Ident(s) => format!("identifier '{}'", s),
            T::Int(v) => format!("integer '{}'", v),
            T::Float(v) => format!("float '{}'", v),
            T::Str(_) => "string literal".into(),
            T::Plus => "'+'".into(),
            T::Minus => "'-'".into(),
            T::Star => "'*'".into(),
            T::Slash => "'/'".into(),
            T::Percent => "'%'".into(),
            T::EqEq => "'=='".into(),
            T::NotEq => "'!='".into(),
            T::Lt => "'<'".into(),
            T::Le => "'<='".into(),
            T::Gt => "'>'".into(),
            T::Ge => "'>='".into(),
            T::AndAnd => "'&&'".into(),
            T::OrOr => "'||'".into(),
            T::Bang => "'!'".into(),
            T::Assign => "'='".into(),
            T::PlusEq => "'+='".into(),
            T::MinusEq => "'-='".into(),
            T::StarEq => "'*='".into(),
            T::SlashEq => "'/='".into(),
            T::PercentEq => "'%='".into(),
            T::Arrow => "'->'".into(),
            T::Colon => "':'".into(),
            T::Semi => "';'".into(),
            T::Comma => "','".into(),
            T::LParen => "'('".into(),
            T::RParen => "')'".into(),
            T::LBrace => "'{'".into(),
            T::RBrace => "'}'".into(),
            T::LBracket => "'['".into(),
            T::RBracket => "']'".into(),
            T::Dot => "'.'".into(),
            T::DotDot => "'..'".into(),
            T::Eof => "end of file".into(),
        }
    }
}

#[derive(Debug, Clone)]
pub struct Token {
    pub kind: TokenKind,
    pub pos: Pos,
}
