#!/usr/bin/env python3
"""Generates stdlib/array.fen: the same functions for [i32], [f64] and [String]
(Fenneth has no generics). Not part of the build; the output is checked in."""
import sys

TYPES = [
    # suffix, fenneth type, less(p, q), numeric?
    ("i32", "i32", lambda p, q: f"{p} < {q}", True),
    ("f64", "f64", lambda p, q: f"{p} < {q}", True),
    ("str", "String", lambda p, q: f"string_compare({p}, {q}) < 0", False),
]

HEADER = '''// std/array - helpers for arrays of i32, f64 and String.
//
//     import "std/array";
//
// Fenneth has no generics, so every function exists once per element type,
// with the type as a suffix: array_sort_i32, array_sort_f64, array_sort_str.
// (Appending, removing and measuring are built in: push, pop, len.)
//
// Arrays are shared, not copied, when you assign them. Functions that say
// "in place" change the array you pass; the others return a new array.
// Strings are ordered byte by byte (see string_compare in std/string).
//
// Generated by scripts/gen-stdlib-array.py - edit the script, not this file.

import "std/string";

// ---- i32 only ----------------------------------------------------------------

// The numbers start, start+1, ..., end-1. Empty when end <= start.
fn array_range(start: i32, end: i32) -> [i32] {
    let out: [i32] = [];
    for i in start..end { push(out, i); }
    return out;
}
'''

def block(sfx, T, less, numeric):
    L = lambda p, q: less(p, q)
    out = []
    out.append(f"""
// ---- [{T}] {'-' * (60 - len(T))}

// A new array with the same elements.
fn array_copy_{sfx}(a: [{T}]) -> [{T}] {{
    let out: [{T}] = [];
    for x in a {{ push(out, x); }}
    return out;
}}

// A new array with n copies of v. Panics when n < 0.
fn array_fill_{sfx}(n: i32, v: {T}) -> [{T}] {{
    if n < 0 {{ panic("array_fill_{sfx}: negative length"); }}
    let out: [{T}] = [];
    for i in 0..n {{ push(out, v); }}
    return out;
}}

// The elements from index `from` up to, not including, `to`. Panics when the
// range is not inside the array.
fn array_slice_{sfx}(a: [{T}], from: i32, to: i32) -> [{T}] {{
    if from < 0 || to < from || to > len(a) {{ panic("array_slice_{sfx}: range out of bounds"); }}
    let out: [{T}] = [];
    for i in from..to {{ push(out, a[i]); }}
    return out;
}}

// A new array holding the elements of a followed by those of b.
fn array_concat_{sfx}(a: [{T}], b: [{T}]) -> [{T}] {{
    let out: [{T}] = array_copy_{sfx}(a);
    for x in b {{ push(out, x); }}
    return out;
}}

fn array_contains_{sfx}(a: [{T}], v: {T}) -> bool {{
    for x in a {{
        if x == v {{ return true; }}
    }}
    return false;
}}

// Index of the first element equal to v, or -1.
fn array_index_of_{sfx}(a: [{T}], v: {T}) -> i32 {{
    for i in 0..len(a) {{
        if a[i] == v {{ return i; }}
    }}
    return -1;
}}

// Smallest / largest element. Panic on an empty array.
fn array_min_{sfx}(a: [{T}]) -> {T} {{
    if len(a) == 0 {{ panic("array_min_{sfx}: empty array"); }}
    let best: {T} = a[0];
    for x in a {{
        if {L('x', 'best')} {{ best = x; }}
    }}
    return best;
}}

fn array_max_{sfx}(a: [{T}]) -> {T} {{
    if len(a) == 0 {{ panic("array_max_{sfx}: empty array"); }}
    let best: {T} = a[0];
    for x in a {{
        if {L('best', 'x')} {{ best = x; }}
    }}
    return best;
}}

// Reverses the array in place.
fn array_reverse_{sfx}(a: [{T}]) {{
    let i: i32 = 0;
    let j: i32 = len(a) - 1;
    while i < j {{
        let held: {T} = a[i];
        a[i] = a[j];
        a[j] = held;
        i += 1;
        j -= 1;
    }}
}}

// True when no element is smaller than the one before it.
fn array_is_sorted_{sfx}(a: [{T}]) -> bool {{
    for i in 1..len(a) {{
        if {L('a[i]', 'a[i - 1]')} {{ return false; }}
    }}
    return true;
}}

// Sorts a[lo..hi] with a merge sort; `tmp` is scratch space of the same size.
fn _array_msort_{sfx}(a: [{T}], tmp: [{T}], lo: i32, hi: i32) {{
    if hi - lo < 2 {{ return; }}
    let mid: i32 = lo + (hi - lo) / 2;
    _array_msort_{sfx}(a, tmp, lo, mid);
    _array_msort_{sfx}(a, tmp, mid, hi);
    let i: i32 = lo;
    let j: i32 = mid;
    let k: i32 = lo;
    while i < mid && j < hi {{
        if {L('a[j]', 'a[i]')} {{
            tmp[k] = a[j];
            j += 1;
        }} else {{
            tmp[k] = a[i];
            i += 1;
        }}
        k += 1;
    }}
    while i < mid {{
        tmp[k] = a[i];
        i += 1;
        k += 1;
    }}
    while j < hi {{
        tmp[k] = a[j];
        j += 1;
        k += 1;
    }}
    for t in lo..hi {{ a[t] = tmp[t]; }}
}}

// Sorts the array in place, smallest first. The sort is stable and takes
// O(n log n) time.
fn array_sort_{sfx}(a: [{T}]) {{
    if len(a) < 2 {{ return; }}
    _array_msort_{sfx}(a, array_copy_{sfx}(a), 0, len(a));
}}
""")
    if numeric:
        out.append(f"""
// The sum of all elements (0 for an empty array).{' Wraps on overflow.' if sfx == 'i32' else ''}
fn array_sum_{sfx}(a: [{T}]) -> {T} {{
    let total: {T} = {'0' if sfx == 'i32' else '0.0'};
    for x in a {{ total += x; }}
    return total;
}}
""")
    return "".join(out)

def main():
    parts = [HEADER]
    for t in TYPES:
        parts.append(block(*t))
    sys.stdout.write("".join(parts))

main()
